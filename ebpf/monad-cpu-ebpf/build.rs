//! 1. Emit BTF for this package only. Tail calls with subprograms need it
//!    (kernel 6.17+). It is not workspace-wide, because BTF turns
//!    compiler_builtins' memset into a global function the verifier rejects in
//!    programs that call it. See ebpf/.cargo/config.toml.
//! 2. Emit `UPC_SURFACE_ID` for the active feature set (ADR-080 §"I/O-time
//!    gates", Gate A): the surface id of the ecall numbers this build compiles
//!    in (surface.rs), hashed by the same function the loader uses
//!    (crates/upc-api/src/surface_hash.rs). Data only: src/upc_facts.rs puts it
//!    in `.rodata.upc` and no BPF code reads it.

use std::{env, fs, path::PathBuf};

include!("surface.rs");
include!("../../crates/upc-api/src/surface_hash.rs");

fn main() {
    println!("cargo:rustc-link-arg=--btf");

    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-changed=surface.rs");
    println!("cargo:rerun-if-changed=../../crates/upc-api/src/surface_hash.rs");

    let ascend = env::var_os("CARGO_FEATURE_ASCEND_LINUX").is_some();
    let (name, numbers) = if ascend {
        ("SURFACE_ASCEND", SURFACE_ASCEND)
    } else {
        ("SURFACE_DEFAULT", SURFACE_DEFAULT)
    };
    let id = surface_id(numbers);
    let bytes: Vec<String> = id.iter().map(|b| format!("0x{b:02x}")).collect();
    let out = PathBuf::from(env::var("OUT_DIR").expect("OUT_DIR")).join("upc_surface_id.rs");
    fs::write(
        &out,
        format!(
            "// Generated by build.rs from surface.rs::{name} {numbers:?}.\n\
             pub const UPC_SURFACE_ID_BYTES: [u8; 32] = [{}];\n",
            bytes.join(", ")
        ),
    )
    .expect("write upc_surface_id.rs");
}
