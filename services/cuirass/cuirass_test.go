// newTestLogger returns a logger that discards output, suitable for tests.
func newTestLogger() *logger.Logger {
	return logger.New(io.Discard)
}

// newTestService creates a Service with sensible test defaults.
// The wotan client is nil because no network operations are performed.
func newTestService() *Service {
	return NewService(newTestLogger(), nil, nil)
}

// newTestServiceWithConfig creates a Service with a custom config.
func newTestServiceWithConfig(cfg *Config) *Service {
	return NewService(newTestLogger(), nil, cfg)
}

// makeSvc is a convenience for registering a ServiceRegistration with
// reasonable defaults. Only the overridden fields need to be supplied.
func makeSvc(id, name string) *ServiceRegistration {
	return &ServiceRegistration{
		ID:       id,
		Name:     name,
		Version:  "1.0.0",
		Address:  "10.10.10.20",
		Port:     8000,
		Protocol: "http",
	}
}

