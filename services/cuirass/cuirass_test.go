func TestDeregister(t *testing.T) {
	t.Parallel()

	tests := []struct {
		name      string
		setupIDs  []string
		removeID  string
		expectErr bool
	}{
		{
			name:      "ExistingService",
			setupIDs:  []string{"svc-1"},
			removeID:  "svc-1",
			expectErr: false,
		},
		{
			name:      "NonExistentService",
			setupIDs:  []string{},
			removeID:  "ghost",
			expectErr: true,
		},
		{
			name:      "AlreadyDeregistered",
			setupIDs:  []string{"svc-2"},
			removeID:  "svc-2",
			expectErr: false,
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			s := newTestService()
			ctx := context.Background()

			for _, id := range tt.setupIDs {
				_ = s.Register(ctx, makeSvc(id, "test"))
			}

			err := s.Deregister(ctx, tt.removeID)
			if tt.expectErr && err == nil {
				t.Error("expected error, got nil")
			}
			if !tt.expectErr && err != nil {
				t.Errorf("expected no error, got %v", err)
			}

			// Verify removal.
			if !tt.expectErr {
				_, ok := s.GetService(tt.removeID)
				if ok {
					t.Error("service should not be found after deregister")
				}
			}
		})
	}
}

