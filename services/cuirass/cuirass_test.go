// ---------------------------------------------------------------------------
// 21. Concurrent register, health check, and stats
// ---------------------------------------------------------------------------

func TestConcurrentFullLifecycle(t *testing.T) {
	t.Parallel()
	s := newTestService()
	ctx := context.Background()

	const n = 50
	var wg sync.WaitGroup
	wg.Add(n * 4)

	// Register.
	for i := 0; i < n; i++ {
		go func(idx int) {
			defer wg.Done()
			_ = s.Register(ctx, makeSvc(fmt.Sprintf("fl-%d", idx), "lifecycle"))
		}(i)
	}

	// Heartbeat.
	for i := 0; i < n; i++ {
		go func(idx int) {
			defer wg.Done()
			_ = s.Heartbeat(ctx, fmt.Sprintf("fl-%d", idx))
		}(i)
	}

	// Health check.
	for i := 0; i < n; i++ {
		go func(idx int) {
			defer wg.Done()
			s.RecordHealthCheck(&HealthCheck{
				ServiceID: fmt.Sprintf("fl-%d", idx),
				Status:    idx%3 != 0,
				CheckedAt: time.Now(),
			})
		}(i)
	}

	// Stats + reads.
	for i := 0; i < n; i++ {
		go func(idx int) {
			defer wg.Done()
			_ = s.Stats()
			_ = s.ListServices()
			_ = s.GetServiceByName("lifecycle")
			_, _ = s.GetService(fmt.Sprintf("fl-%d", idx))
			_, _ = s.GetHealthCheck(fmt.Sprintf("fl-%d", idx))
		}(i)
	}

	wg.Wait()
}

