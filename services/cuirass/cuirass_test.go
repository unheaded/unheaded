func TestRegister(t *testing.T) {
	t.Parallel()

	tests := []struct {
		name         string
		svc          *ServiceRegistration
		expectID     bool   // expect provided ID to be preserved
		expectStatus ServiceStatus
	}{
		{
			name:         "WithExplicitID",
			svc:          makeSvc("svc-001", "gateway"),
			expectID:     true,
			expectStatus: StatusUnknown,
		},
		{
			name: "WithEmptyID_AutoGenerated",
			svc: &ServiceRegistration{
				Name:     "timeguru",
				Version:  "0.1.0",
				Address:  "10.10.10.21",
				Port:     8001,
				Protocol: "http",
			},
			expectID:     false,
			expectStatus: StatusUnknown,
		},
		{
			name: "WithMetadataAndTags",
			svc: &ServiceRegistration{
				ID:       "svc-meta",
				Name:     "captain",
				Version:  "2.0.0",
				Address:  "10.10.10.22",
				Port:     8002,
				Protocol: "grpc",
				Metadata: map[string]string{"env": "prod"},
				Tags:     []string{"critical", "tier-1"},
			},
			expectID:     true,
			expectStatus: StatusUnknown,
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			s := newTestService()
			ctx := context.Background()

			if err := s.Register(ctx, tt.svc); err != nil {
				t.Fatalf("Register returned error: %v", err)
			}

			if tt.expectID && tt.svc.ID == "" {
				t.Error("expected ID to remain non-empty")
			}
			if !tt.expectID && tt.svc.ID == "" {
				t.Error("expected auto-generated ID")
			}
			if tt.svc.Status != tt.expectStatus {
				t.Errorf("expected status %s, got %s", tt.expectStatus, tt.svc.Status)
			}
			if tt.svc.RegisteredAt.IsZero() {
				t.Error("expected RegisteredAt to be set")
			}
			if tt.svc.LastSeen.IsZero() {
				t.Error("expected LastSeen to be set")
			}

			// Verify retrieval.
			got, ok := s.GetService(tt.svc.ID)
			if !ok {
				t.Fatalf("GetService returned false for registered ID %s", tt.svc.ID)
			}
			if got.Name != tt.svc.Name {
				t.Errorf("expected name %s, got %s", tt.svc.Name, got.Name)
			}
		})
	}
}

