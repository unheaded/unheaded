func TestHealthStatusTransitions(t *testing.T) {
	t.Parallel()

	// Test the full state machine: unknown -> healthy -> unhealthy -> healthy
	s := newTestService()
	ctx := context.Background()

	_ = s.Register(ctx, makeSvc("sm-1", "test"))

	// Initial state is unknown.
	svc, _ := s.GetService("sm-1")
	if svc.Status != StatusUnknown {
		t.Fatalf("expected initial status %s, got %s", StatusUnknown, svc.Status)
	}

	// Transition: unknown -> healthy
	s.RecordHealthCheck(&HealthCheck{ServiceID: "sm-1", Status: true, CheckedAt: time.Now()})
	svc, _ = s.GetService("sm-1")
	if svc.Status != StatusHealthy {
		t.Errorf("expected %s after positive check, got %s", StatusHealthy, svc.Status)
	}

	// Transition: healthy -> unhealthy
	s.RecordHealthCheck(&HealthCheck{ServiceID: "sm-1", Status: false, CheckedAt: time.Now()})
	svc, _ = s.GetService("sm-1")
	if svc.Status != StatusUnhealthy {
		t.Errorf("expected %s after negative check, got %s", StatusUnhealthy, svc.Status)
	}

	// Transition: unhealthy -> healthy (recovery)
	s.RecordHealthCheck(&HealthCheck{ServiceID: "sm-1", Status: true, CheckedAt: time.Now()})
	svc, _ = s.GetService("sm-1")
	if svc.Status != StatusHealthy {
		t.Errorf("expected %s after recovery, got %s", StatusHealthy, svc.Status)
	}
}

