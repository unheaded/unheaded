package zhenrag

import (
	"bytes"
	"encoding/json"
	"strings"
)

// PythonModule renders raft/scripts/zhen_prompt_generated.py: the Web
// prompt, the chat verb list, the code-comment reminder and the worked
// example as Python literals. Strings are emitted as JSON string literals,
// which Python reads with the same meaning (\n, \", \\ and \uXXXX are common
// to both), one source line per prompt line so a diff stays readable.
func PythonModule() []byte {
	var b bytes.Buffer
	b.WriteString("# GENERATED by go run ./pkg/zhenrag/gen — do not edit.\n")
	b.WriteString("# Source: pkg/zhenrag (prompt.go, verbs.go). Regenerate with\n")
	b.WriteString("#   go generate ./pkg/zhenrag/...\n")
	b.WriteString("# TestGenerated_PythonInSync fails when this file is stale.\n")
	b.WriteString("# SPDX-License-Identifier: GPL-3.0-or-later\n")
	b.WriteString("# Copyright (c) 2025-2026 Stevie Bellis.\n")
	b.WriteString("\"\"\"Zhen prompt text shared with the Go surfaces (pkg/zhenrag).\"\"\"\n\n")

	b.WriteString("# The verbs the chat prompt's DESTRUCTIVE-VERB FILTER names, in order.\n")
	b.WriteString("DESTRUCTIVE_VERBS = [\n")
	for _, v := range ChatVerbs() {
		b.WriteString("    " + pyString(v) + ",\n")
	}
	b.WriteString("]\n\n")

	b.WriteString("# Appended after the question in every chat turn.\n")
	b.WriteString("CODE_COMMENT_REMINDER = " + pyConcat(CodeCommentReminder, "    ") + "\n\n")

	b.WriteString("# One worked exchange placed before the real conversation.\n")
	b.WriteString("CODE_COMMENT_EXAMPLE = [\n")
	for _, m := range CodeCommentExample() {
		b.WriteString("    {\"role\": " + pyString(m.Role) + ", \"content\": " + pyConcat(m.Content, "        ") + "},\n")
	}
	b.WriteString("]\n\n")

	b.WriteString("# The web UI's system prompt (zhenrag.SystemPrompt(zhenrag.Web)).\n")
	b.WriteString("DEFAULT_SYSTEM_PROMPT = " + pyConcat(SystemPrompt(Web), "    ") + "\n")
	return b.Bytes()
}

// pyString renders s as a Python string literal (a JSON string, HTML
// escaping off so `<`, `>` and `&` stay readable).
func pyString(s string) string {
	var b bytes.Buffer
	enc := json.NewEncoder(&b)
	enc.SetEscapeHTML(false)
	if err := enc.Encode(s); err != nil {
		panic(err) // a Go string always encodes
	}
	return strings.TrimSuffix(b.String(), "\n")
}

// pyConcat renders s as a parenthesised implicit concatenation, one literal
// per line of s (each keeps its trailing \n).
func pyConcat(s, indent string) string {
	lines := strings.SplitAfter(s, "\n")
	if len(lines) > 0 && lines[len(lines)-1] == "" {
		lines = lines[:len(lines)-1]
	}
	if len(lines) <= 1 {
		return pyString(s)
	}
	var b strings.Builder
	b.WriteString("(\n")
	for _, l := range lines {
		b.WriteString(indent + pyString(l) + "\n")
	}
	b.WriteString(indent[:len(indent)-4] + ")")
	return b.String()
}
