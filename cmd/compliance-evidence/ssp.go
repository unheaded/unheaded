// The system security plan (M-104): `compliance-evidence ssp` renders the
// catalog and the evidence file as Markdown, one section per control, plus
// the framework coverage table as the Statement of Applicability. Like
// `findings` it collects nothing. The output is a pure function of the
// catalog, the evidence and the evaluation date: no record details, commits
// or wall-clock times, so regenerating it changes only what changed.

const sspHeader = "<!-- GENERATED by `go run ./cmd/compliance-evidence ssp`; do not edit. Source: compliance/catalog/controls.yaml + the evidence file. -->\n\n"

func runSSP(args []string, stdout io.Writer) error {
	fl := flag.NewFlagSet("ssp", flag.ContinueOnError)
	repoDir := fl.String("repo-dir", ".", "repository root; relative paths below resolve against it")
	catalog := fl.String("catalog", "compliance/catalog/controls.yaml", "controls file")
	frameworks := fl.String("frameworks", "compliance/catalog/frameworks", "framework files directory")
	evidence := fl.String("evidence", "var/compliance/evidence.json", "evidence file (absent: every control NOT_ASSESSED)")
	atFlag := fl.String("at", "", "evaluate at the end of this UTC day, YYYY-MM-DD (default: now)")
	out := fl.String("out", "", "Markdown file to write (required)")
	if err := fl.Parse(args); err != nil {
		return err
	}
	if fl.NArg() > 0 {
		return fmt.Errorf("unexpected argument %q", fl.Arg(0))
	}
	if *out == "" {
		return errors.New("-out is required")
	}
	now := time.Now().UTC()
	if *atFlag != "" {
		d, err := time.Parse(time.DateOnly, *atFlag)
		if err != nil {
			return fmt.Errorf("-at %q: want YYYY-MM-DD", *atFlag)
		}
		now = d.Add(24*time.Hour - time.Nanosecond)
	}

	cat, err := crosswalk.LoadFS(os.DirFS(*repoDir), filepath.ToSlash(*frameworks), filepath.ToSlash(*catalog))
	if err != nil {
		return err
	}
	evPath := *evidence
	if !filepath.IsAbs(evPath) {
		evPath = filepath.Join(*repoDir, evPath)
	}
	var recs []crosswalk.Record
	if f, err := os.Open(evPath); err == nil { // #nosec G304 -- operator-chosen evidence file from a flag of this local CLI
		recs, err = crosswalk.ReadEvidence(f)
		err = errors.Join(err, f.Close())
		if err != nil {
			return fmt.Errorf("%s: %w", evPath, err)
		}
	} else if !errors.Is(err, fs.ErrNotExist) {
		return err
	}

	doc, fails := renderSSP(cat, recs, now, *evidence)
	path := *out
	if !filepath.IsAbs(path) {
		path = filepath.Join(*repoDir, path)
	}
	if err := writeFileAtomic(path, []byte(doc)); err != nil {
		return err
	}
	_, err = fmt.Fprintf(stdout, "%d controls (%d failing) written to %s\n", len(cat.Controls), fails, path)
	return err
}

// latestRecords returns, per source key, the newest pass/fail record
// observed at or before now: the record crosswalk.ControlStatus judges by.
func latestRecords(recs []crosswalk.Record, now time.Time) map[string]crosswalk.Record {
	latest := make(map[string]crosswalk.Record)
	for _, r := range recs {
		if r.ObservedAt.After(now) || (r.Verdict != crosswalk.VerdictPass && r.Verdict != crosswalk.VerdictFail) {
			continue
		}
		k := r.Source.Key()
		if cur, ok := latest[k]; !ok || r.ObservedAt.After(cur.ObservedAt) {
			latest[k] = r
		}
	}
	return latest
}

// statusLine names the status and the date that decided it: for a failure
// the newest failing record, otherwise the oldest of the sources' latest
// records (the one that goes stale first).
func statusLine(ctl *crosswalk.Control, st crosswalk.Status, latest map[string]crosswalk.Record) string {
	var have []crosswalk.Record
	for _, s := range ctl.Evidence {
		if r, ok := latest[s.Key()]; ok {
			have = append(have, r)
		}
	}
	day := func(t time.Time) string { return t.UTC().Format(time.DateOnly) }
	switch st {
	case crosswalk.StatusNotAssessed:
		return fmt.Sprintf("**Status:** %s, no evidence for %d of %d sources", st, len(ctl.Evidence)-len(have), len(ctl.Evidence))
	case crosswalk.StatusFail:
		var at time.Time
		for _, r := range have {
			if r.Verdict == crosswalk.VerdictFail && r.ObservedAt.After(at) {
				at = r.ObservedAt
			}
		}
		return fmt.Sprintf("**Status:** %s, evidence as of %s", st, day(at))
	default:
		at := have[0].ObservedAt
		for _, r := range have[1:] {
			if r.ObservedAt.Before(at) {
				at = r.ObservedAt
			}
		}
		return fmt.Sprintf("**Status:** %s, evidence as of %s", st, day(at))
	}
}

func renderSSP(cat *crosswalk.Catalog, recs []crosswalk.Record, now time.Time, evidenceName string) (string, int) {
	sum := crosswalk.Summarize(cat, recs, now)
	latest := latestRecords(recs, now)
	counts := map[crosswalk.Status]int{}
	for _, c := range cat.Controls {
		counts[sum.Controls[c.ID]]++
	}

	var b strings.Builder
	b.WriteString(sspHeader)
	b.WriteString("# System Security Plan\n\n")
	fmt.Fprintf(&b, "Evaluated %s against `%s`: %d controls, %d frameworks.\n\n",
		now.UTC().Format(time.DateOnly), evidenceName, len(cat.Controls), len(cat.Frameworks))
	b.WriteString("- Risk management strategy (appetite, categorization, criticality): `compliance/policies/risk-management-strategy.md`.\n")
	b.WriteString("- Single-operator posture (accepted gaps, compensating controls): `compliance/policies/single-operator-posture.md`.\n")
	b.WriteString("- Information security policy: `compliance/policies/information-security-policy.md`.\n\n")
	b.WriteString("A mapping says a control's evidence supports part of a framework requirement. No framework is claimed met. ")
	b.WriteString("Attestations are self-attested and labelled so.\n\n")

	b.WriteString("## Summary\n\n| Control status | Controls |\n|---|---|\n")
	fmt.Fprintf(&b, "| passing | %d |\n| stale | %d |\n| not assessed | %d |\n| failing | %d |\n\n",
		counts[crosswalk.StatusPass], counts[crosswalk.StatusStale], counts[crosswalk.StatusNotAssessed], counts[crosswalk.StatusFail])

	b.WriteString("## Controls\n")
	for _, c := range cat.Controls {
		st := sum.Controls[c.ID]
		fmt.Fprintf(&b, "\n### %s: %s\n\n", c.ID, oneLine(c.Title))
		b.WriteString(statusLine(c, st, latest) + "\n\n")
		b.WriteString(oneLine(c.Statement) + "\n\n")
		if c.Rationale != "" {
			b.WriteString("Rationale: " + oneLine(c.Rationale) + "\n\n")
		}
		b.WriteString("Evidence:\n\n")
		for _, s := range c.Evidence {
			line := fmt.Sprintf("- `%s`: no record", s.Key())
			if r, ok := latest[s.Key()]; ok {
				line = fmt.Sprintf("- `%s`: %s %s", s.Key(), r.Verdict, r.ObservedAt.UTC().Format(time.DateOnly))
			}
			if s.Kind == crosswalk.KindAttestation {
				line += " (self-attested)"
			}
			b.WriteString(line + "\n")
		}
		b.WriteString("\nMappings:\n\n")
		fws := make([]string, 0, len(c.Mappings))
		for fw := range c.Mappings {
			fws = append(fws, fw)
		}
		sort.Strings(fws)
		for _, fw := range fws {
			fmt.Fprintf(&b, "- %s: %s\n", fw, strings.Join(c.Mappings[fw], ", "))
		}
	}

	b.WriteString("\n## SoA\n\n")
	b.WriteString("Statement of Applicability. Every framework in the catalog is in scope as a mapping target and counted against the publisher's full requirement list; ")
	b.WriteString("an unmapped requirement is counted, never dropped. Requirement statuses: evidenced (every mapped control passes), ")
	b.WriteString("failing (a mapped control fails), incomplete (mapped, none failing, some not assessed or stale), unmapped.\n\n")
	b.WriteString("| Framework | Name | Version | Granularity | Requirements | Evidenced | Failing | Incomplete | Unmapped |\n")
	b.WriteString("|---|---|---|---|---|---|---|---|---|\n")
	for _, fw := range sum.Frameworks {
		fmt.Fprintf(&b, "| %s | %s | %s | %s | %d | %d | %d | %d | %d |\n", cell(fw.ID), cell(fw.Name), cell(fw.Version), cell(fw.Granularity),
			fw.Total, fw.Counts[crosswalk.ReqEvidenced], fw.Counts[crosswalk.ReqFailing], fw.Counts[crosswalk.ReqIncomplete], fw.Counts[crosswalk.ReqUnmapped])
	}
	return b.String(), counts[crosswalk.StatusFail]
}

// oneLine folds whitespace so YAML block scalars render as one paragraph.
func oneLine(s string) string { return strings.Join(strings.Fields(s), " ") }

func writeFileAtomic(path string, data []byte) error {
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil { // #nosec G301 -- a docs directory, world-readable like the rest of the repo
		return err
	}
	tmp, err := os.CreateTemp(filepath.Dir(path), ".ssp-*.md")
	if err != nil {
		return err
	}
	defer func() { _ = os.Remove(tmp.Name()) }()
	if _, err := tmp.Write(data); err != nil {
		return errors.Join(err, tmp.Close())
	}
	if err := tmp.Chmod(0o644); err != nil {
		return errors.Join(err, tmp.Close())
	}
	if err := tmp.Close(); err != nil {
		return err
	}
	return os.Rename(tmp.Name(), path)
}
