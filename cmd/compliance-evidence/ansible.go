// `compliance-evidence ansible` renders the fix model, the profiles and
// the host bindings (repo YAML, so the output is reproducible) to
// deploy/ansible/compliance/ (ADR-099 §3). The directory is generated:
// files the render no longer produces are removed. A test fails when the
// committed tree drifts from a fresh render.

const ansibleDir = "deploy/ansible/compliance"

func renderAnsible(repoDir string) (map[string]string, error) {
	s, err := well.NewYAMLStore(repoDir)
	if err != nil {
		return nil, err
	}
	ps, err := s.Profiles(context.Background())
	if err != nil {
		return nil, err
	}
	bs, err := s.Bindings(context.Background())
	if err != nil {
		return nil, err
	}
	out, err := iac.RenderRemediationAnsible(s.Model(), ps, bs)
	if err != nil {
		return nil, err
	}
	out.Files["README.md"] = ansibleReadme
	return out.Files, nil
}

const ansibleReadme = `<!-- Generated by ` + "`go run ./cmd/compliance-evidence ansible`" + `. Do not edit. -->
# Compliance fixes as Ansible (ADR-099)

Rendered from ` + "`compliance/remediation/fixes.yaml`" + `: one role per fix, one
playbook per control profile, and ` + "`inventory.yml`" + ` grouping hosts by
the profile they are bound to.

    ansible-playbook -i inventory.yml profile-lab.yml --check --diff   # what would change
    ansible-playbook -i inventory.yml profile-lab.yml                  # apply

The reference implementation is ` + "`unheaded-remediate`" + ` (the native executor),
which also journals every apply and restores modes and owners on failure;
these roles restore file contents only. Switching a host's profile does not
apply anything: run a playbook (or unheaded-remediate) afterwards.
`

func runAnsible(args []string, stdout io.Writer) error {
	fl := flag.NewFlagSet("ansible", flag.ContinueOnError)
	repoDir := fl.String("repo-dir", ".", "repository root")
	if err := fl.Parse(args); err != nil {
		return err
	}
	files, err := renderAnsible(*repoDir)
	if err != nil {
		return err
	}
	root, err := os.OpenRoot(*repoDir)
	if err != nil {
		return err
	}
	defer root.Close()
	existing, err := ansibleFiles(root.FS())
	if err != nil {
		return err
	}
	for _, p := range existing {
		if _, keep := files[p]; !keep {
			if err := root.Remove(filepath.Join(ansibleDir, p)); err != nil {
				return err
			}
		}
	}
	names := make([]string, 0, len(files))
	for p := range files {
		names = append(names, p)
	}
	sort.Strings(names)
	for _, p := range names {
		full := filepath.Join(ansibleDir, p)
		if err := root.MkdirAll(filepath.Dir(full), 0o755); err != nil { // #nosec G301 -- repo directory
			return err
		}
		if err := root.WriteFile(full, []byte(files[p]), 0o644); err != nil { // #nosec G306 -- repo file
			return err
		}
	}
	fmt.Fprintf(stdout, "%d files written to %s\n", len(files), ansibleDir)
	return nil
}

// ansibleFiles lists the generated tree, relative to it.
func ansibleFiles(fsys fs.FS) ([]string, error) {
	var out []string
	err := fs.WalkDir(fsys, ansibleDir, func(p string, d fs.DirEntry, err error) error {
		if errors.Is(err, fs.ErrNotExist) {
			return fs.SkipAll
		}
		if err != nil {
			return err
		}
		if !d.IsDir() {
			out = append(out, strings.TrimPrefix(p, ansibleDir+"/"))
		}
		return nil
	})
	return out, err
}
