// Collected data lives on the host, never in the repository (Stevie,
// 2026-11-09): a report built from evidence goes under var/ (gitignored) or
// outside the tree.
func TestHostOutPath(t *testing.T) {
	repo := t.TempDir()
	outside := t.TempDir()
	if err := os.MkdirAll(filepath.Join(repo, "docs"), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.Symlink(filepath.Join(repo, "docs"), filepath.Join(repo, "var-link")); err != nil {
		t.Fatal(err)
	}

	for _, ok := range []string{
		"var/compliance/findings.md",
		filepath.Join(repo, "var", "compliance", "SSP.md"),
		filepath.Join(outside, "SSP.md"),
	} {
		if _, err := hostOutPath(repo, ok); err != nil {
			t.Errorf("%s refused: %v", ok, err)
		}
	}
	for _, bad := range []string{
		"docs/compliance/SSP-generated.md",
		"docs/adr/ADR-098-findings-register-and-baseline-modes.md",
		filepath.Join(repo, "compliance", "findings.md"),
		"var/../docs/x.md",
		"var-link/x.md",
		"findings.md",
		".",
		"",
	} {
		if _, err := hostOutPath(repo, bad); err == nil {
			t.Errorf("%q accepted inside the repository", bad)
		}
	}
}

func TestRunSSP_RefusesRepoPath(t *testing.T) {
	repo := t.TempDir()
	if err := os.CopyFS(repo, os.DirFS("testdata/ssp")); err != nil {
		t.Fatal(err)
	}
	args := []string{"-repo-dir", repo, "-catalog", "controls.yaml", "-frameworks", "frameworks",
		"-evidence", "evidence.json", "-at", "2026-10-27", "-out", "docs/compliance/SSP-generated.md"}
	if err := runSSP(args, io.Discard); err == nil {
		t.Fatal("ssp wrote its report into the repository tree")
	}
	if _, err := os.Stat(filepath.Join(repo, "docs/compliance/SSP-generated.md")); err == nil {
		t.Error("the refused report exists anyway")
	}
}

// The repository holds the generators, never their output.
func TestNoCollectedDataCommitted(t *testing.T) {
	markers := []string{
		"<!-- BEGIN GENERATED FINDINGS -->",
		"<!-- GENERATED by `go run ./cmd/compliance-evidence ssp`",
	}
	for _, dir := range []string{"../../docs", "../../compliance", "../../wiki"} {
		err := filepath.WalkDir(dir, func(p string, d fs.DirEntry, err error) error {
			if err != nil || d.IsDir() || !strings.HasSuffix(p, ".md") {
				return err
			}
			b, err := os.ReadFile(p)
			if err != nil {
				return err
			}
			for _, m := range markers {
				if strings.Contains(string(b), m) {
					t.Errorf("%s holds generated compliance output (%s)", p, m)
				}
			}
			return nil
		})
		if err != nil {
			t.Fatal(err)
		}
	}
}
