"""gen-prom-keep-list.py: the series Prometheus keeps are the series its rules read.

ADR-147 decisions 9 and 10, D4 = A: Prometheus keeps 30 days, of only the
series a rule in monitoring/prometheus/rules/*.yml reads; everything else is
VictoriaMetrics' alone. This script reads every rule's `expr`, takes the
metric names out of it, adds the series each runbook under runbooks/ reads
from Prometheus' API (a `curl ... 127.0.0.1:9090/api/v1/query` line with
`query=`: a runbook check that reads a dropped series reads nothing) and
monitoring/prometheus/keep-extra.txt (any other reader of Prometheus' own
API, one per line, `# reader: <file>`), and writes:

  monitoring/prometheus/rule-series.txt   the sorted list (generated)
  monitoring/prometheus/prometheus.yml    the text between the markers
      # BEGIN rule-series (scripts/gen-prom-keep-list.py; do not edit)
      # END rule-series
    in each scrape job that has them: an anchored keep in the first, an
    alias in the rest.

A series that every rule names with a `job` matcher (`job="a"` or
`job=~"a|b"`, plain names only) is kept only in those jobs (S-SEE-AND-SURVIVE
Phase 17: the SLIs on Wotan's and the dashboard's request histograms must not
bring back every job's). A job with such series gets its own keep, not the
alias. A bare name anywhere, a runbook's query or keep-extra.txt keeps it in
every job.

  --print   print the names, write nothing
  --check   regenerate in memory; exit 1 with a diff when a file differs
  --rules D read rule files from D (default monitoring/prometheus/rules)
  --runbooks D read runbooks from D, recursively (default runbooks)
  --modules D  module root (default modules): a series only a module's rules
               read (modules/*/prometheus/rules) stays off the list, because
               the module's own scrape fragment carries no keep (ADR-149) and
               the platform's files name nothing of a module's

A rule that names a series by regex (`__name__=~`) cannot be listed: the
script exits 1 naming the file, never guesses. Recorded series (a colon in
the name), ALERTS and the series Prometheus makes for every target (up,
scrape_*) are not scraped and need no entry. Standard library and PyYAML only.
"""

import argparse
import difflib
import pathlib
import re
import sys

import yaml

ROOT = pathlib.Path(__file__).resolve().parent.parent
PROM_DIR = ROOT / "monitoring" / "prometheus"
BEGIN = "# BEGIN rule-series (scripts/gen-prom-keep-list.py; do not edit)"
END = "# END rule-series"
HEADER = "# SPDX-License-Identifier: GPL-3.0-or-later\n# Generated by scripts/gen-prom-keep-list.py from monitoring/prometheus/rules/*.yml; do not edit.\n"

KEYWORDS = {"and", "or", "unless", "offset", "bool", "by", "without", "on",
            "ignoring", "group_left", "group_right", "inf", "nan", "atan2"}
# Series Prometheus synthesises for every scrape target: never in a
# metric_relabel keep, never dropped by one.
SYNTHETIC = re.compile(r"^(up|scrape_[a-z_]+)$")

STRING_RE = re.compile(r'"(?:[^"\\]|\\.)*"|\'(?:[^\'\\]|\\.)*\'|`[^`]*`')
BRACES_RE = re.compile(r"\{[^{}]*\}")
BRACKETS_RE = re.compile(r"\[[^\[\]]*\]")
GROUPING_RE = re.compile(r"\b(?:by|without|on|ignoring|group_left|group_right)\s*\([^()]*\)")
IDENT_RE = re.compile(r"[a-zA-Z_][a-zA-Z0-9_:]*")


class RuleError(Exception):
    pass


# A metric name and the label matchers right after it, strings kept whole.
SELECTOR_RE = re.compile(r'(?<![a-zA-Z0-9_:."\'])([a-zA-Z_][a-zA-Z0-9_:]*)(\s*\{(?:[^{}"\']|"(?:[^"\\]|\\.)*"|\'(?:[^\'\\]|\\.)*\')*\})?')
JOB_EQ_RE = re.compile(r'(?:^|[{,\s])job\s*=\s*"([a-zA-Z0-9_.-]+)"')
JOB_RE_RE = re.compile(r'(?:^|[{,\s])job\s*=~\s*"([a-zA-Z0-9_.|-]+)"')


def jobs_of(matchers):
    """The jobs a selector's matchers pin it to, or None for any job."""
    if not matchers:
        return None
    m = JOB_EQ_RE.search(matchers)
    if m:
        return {m.group(1)}
    m = JOB_RE_RE.search(matchers)
    if m and all(m.group(1).split("|")):
        return set(m.group(1).split("|"))
    return None


def scoped_in(expr, names):
    """For each of names in expr: the jobs every use of it is pinned to, or
    None when one use is not pinned (kept in every job)."""
    out = {}
    for m in SELECTOR_RE.finditer(expr):
        name = m.group(1)
        if name not in names:
            continue
        jobs = jobs_of(m.group(2))
        if name in out and out[name] is None:
            continue
        out[name] = None if jobs is None else (out.get(name) or set()) | jobs
    for name in names - out.keys():
        out[name] = None  # only seen inside a string: keep it everywhere
    return out


def merge_scopes(into, more):
    for name, jobs in more.items():
        if jobs is None or into.get(name, set()) is None:
            into[name] = None
        else:
            into[name] = into.get(name, set()) | jobs


def names_in(expr, where):
    """Metric names one PromQL expression reads."""
    if "__name__" in expr:
        raise RuleError(f"{where}: a rule selects series by __name__; list them by name")
    text = STRING_RE.sub(" ", expr)
    text = BRACES_RE.sub(" ", text)
    text = BRACKETS_RE.sub(" ", text)
    text = GROUPING_RE.sub(" ", text)
    out = set()
    for m in IDENT_RE.finditer(text):
        name = m.group(0)
        rest = text[m.end():]
        if re.match(r"\s*\(", rest):  # a function or an aggregation
            continue
        if m.start() > 0 and (text[m.start() - 1].isdigit() or text[m.start() - 1] == "."):
            continue  # a duration or number suffix such as 5m, 1e3
        if name in KEYWORDS or ":" in name or name == "ALERTS" or name == "ALERTS_FOR_STATE":
            continue
        if SYNTHETIC.match(name):
            continue
        out.add(name)
    return out


def rule_series(rules_dir, scopes=None):
    names = set()
    files = sorted(pathlib.Path(rules_dir).glob("*.yml"))
    if not files:
        raise RuleError(f"{rules_dir}: no rule files")
    for f in files:
        doc = yaml.safe_load(f.read_text()) or {}
        for group in doc.get("groups") or []:
            for rule in group.get("rules") or []:
                expr = rule.get("expr")
                if expr is None:
                    continue
                got = names_in(str(expr), f"{f.name}:{rule.get('alert') or rule.get('record')}")
                names |= got
                if scopes is not None:
                    merge_scopes(scopes, scoped_in(str(expr), got))
    return names


PROM_QUERY_LINE = re.compile(r"(?:127\.0\.0\.1|localhost):9090/api/v1/query")
QUERY_ARG = re.compile(r"""--data-urlencode\s+'query=([^']*)'|\?query=([^'"\s]*)""")


def runbook_series(runbooks_dir):
    """Series the runbooks read from Prometheus' API (127.0.0.1:9090)."""
    names = set()
    root = pathlib.Path(runbooks_dir)
    if not root.is_dir():
        return names
    for f in sorted(root.rglob("*.yaml")):
        for n, line in enumerate(f.read_text().splitlines(), 1):
            if not PROM_QUERY_LINE.search(line):
                continue
            for m in QUERY_ARG.finditer(line):
                names |= names_in(m.group(1) or m.group(2), f"{f.name}:{n}")
    return names


def module_series(modules_root):
    """Series the modules' own rules read (modules/*/prometheus/rules)."""
    names = set()
    for d in sorted(pathlib.Path(modules_root).glob("*/prometheus/rules")):
        if any(d.glob("*.yml")):
            names |= rule_series(d)
    return names


def extra_series(path):
    out = set()
    if not path.exists():
        return out
    for line in path.read_text().splitlines():
        line = line.split("#", 1)[0].strip()
        if line:
            out.add(line)
    return out


def render_list(names, scoped=None):
    scoped = scoped or {}
    return HEADER + "".join(n + "\n" for n in sorted(names)) + "".join(
        f"{n}  # only in job {', '.join(sorted(scoped[n]))}\n" for n in sorted(scoped))


JOB_NAME_RE = re.compile(r"^\s*-\s*job_name:\s*['\"]?([^'\"\s]+)")


def render_prometheus(text, names, scoped=None):
    scoped = scoped or {}
    regex = "|".join(sorted(names))
    lines = text.split("\n")
    out, first, i, blocks, job = [], True, 0, 0, None
    while i < len(lines):
        line = lines[i]
        out.append(line)
        jm = JOB_NAME_RE.match(line)
        if jm:
            job = jm.group(1)
        if line.strip() == BEGIN:
            indent = line[: len(line) - len(line.lstrip())]
            j = i + 1
            while j < len(lines) and lines[j].strip() != END:
                j += 1
            if j == len(lines):
                raise RuleError("prometheus.yml: a BEGIN rule-series marker has no END")
            extra = sorted(n for n, jobs in scoped.items() if job in jobs)
            if extra:
                out.append(f"{indent}metric_relabel_configs:")
                out.append(f"{indent}  - source_labels: [__name__]")
                out.append(f"{indent}    regex: '{'|'.join(sorted(names | set(extra)))}'")
                out.append(f"{indent}    action: keep")
            elif first:
                out.append(f"{indent}metric_relabel_configs: &rule_series")
                out.append(f"{indent}  - source_labels: [__name__]")
                out.append(f"{indent}    regex: '{regex}'")
                out.append(f"{indent}    action: keep")
                first = False
            else:
                out.append(f"{indent}metric_relabel_configs: *rule_series")
            out.append(lines[j])
            blocks += 1
            i = j + 1
            continue
        i += 1
    if blocks == 0:
        raise RuleError("prometheus.yml: no rule-series markers")
    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    ap.add_argument("--rules", default=str(PROM_DIR / "rules"))
    ap.add_argument("--runbooks", default=str(ROOT / "runbooks"))
    ap.add_argument("--modules", default=str(ROOT / "modules"))
    ap.add_argument("--print", action="store_true", dest="do_print")
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    try:
        scopes = {}
        platform = rule_series(a.rules, scopes)
        extra = extra_series(PROM_DIR / "keep-extra.txt")
        names = platform | runbook_series(a.runbooks) | extra
        # A module's series reach Prometheus through the module's own job,
        # which has no keep (plan 3 after plan 2, ADR-149): leave them off.
        names -= module_series(a.modules) - platform - extra
        if a.do_print:
            print("\n".join(sorted(names)))
            return 0
        # Pinned to jobs by every rule and read by nothing else.
        scoped = {n: j for n, j in scopes.items() if j is not None and n in names and n not in extra}
        scoped = {n: j for n, j in scoped.items() if n not in runbook_series(a.runbooks)}
        names -= scoped.keys()
        want = {
            PROM_DIR / "rule-series.txt": render_list(names, scoped),
            PROM_DIR / "prometheus.yml": render_prometheus((PROM_DIR / "prometheus.yml").read_text(), names, scoped),
        }
    except RuleError as e:
        print(f"gen-prom-keep-list: {e}", file=sys.stderr)
        return 1
    bad = 0
    for path, text in want.items():
        have = path.read_text() if path.exists() else ""
        if have == text:
            continue
        if a.check:
            bad += 1
            rel = path.relative_to(ROOT)
            sys.stdout.writelines(difflib.unified_diff(have.splitlines(True), text.splitlines(True), f"{rel} (in tree)", f"{rel} (from the rules)"))
        else:
            path.write_text(text)
    if a.check and bad:
        print("gen-prom-keep-list: FAIL: a rule or a runbook reads a series the keep-list lacks, or the list is stale; run scripts/gen-prom-keep-list.py", file=sys.stderr)
        return 1
    if a.check:
        print(f"gen-prom-keep-list: OK ({len(names)} series in every job, {len(scoped)} in named jobs only)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
