"""Render kubernetes/manifests/base/the-well/configmap-initdb.yaml from db/.

The Kubernetes Well used to carry its own initdb script: it created the
databases and roles with passwords interpolated into SQL (a quote in a
password broke it) and no schema at all. Now the ConfigMap holds exactly
what compose mounts: db/init.sh, db/migrations/MANIFEST, LEDGER.sql and every
file the MANIFEST applies (ADR-101). The StatefulSet mounts init.sh into
/docker-entrypoint-initdb.d and the rest at /migrations, as compose does.

    scripts/well/render-k8s-initdb.py            # rewrite the ConfigMap
    scripts/well/render-k8s-initdb.py --check    # exit 1 if it is stale

Standard library only. Output is deterministic (manifest order).
"""
import pathlib
import sys

REPO = pathlib.Path(__file__).resolve().parents[2]
MIG = REPO / "db" / "migrations"
OUT = REPO / "kubernetes" / "manifests" / "base" / "the-well" / "configmap-initdb.yaml"


def manifest_files():
    files = []
    for n, raw in enumerate((MIG / "MANIFEST").read_text().splitlines(), 1):
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        f = line.split()
        if f[0] == "skip":
            continue
        if len(f) < 2:
            sys.exit(f"MANIFEST line {n}: want `<database> <file> [notx]`")
        if f[1] not in files:
            files.append(f[1])
    return files


def block(key, text):
    # A `|` block scalar reproduces the file byte for byte only if it ends
    # in exactly one newline and its first line is not indented; the ledger
    # sha256 depends on that.
    if "\t" in text:
        sys.exit(f"{key}: tabs cannot appear in a YAML block scalar; use spaces")
    if not text.endswith("\n") or text.endswith("\n\n"):
        sys.exit(f"{key}: must end with exactly one newline")
    if text[:1] in (" ", "\n"):
        sys.exit(f"{key}: must not start with whitespace")
    body = "".join(("    " + l if l else "") + "\n" for l in text.rstrip("\n").split("\n"))
    return f"  {key}: |\n{body}"


def render():
    parts = [
        "# SPDX-License-Identifier: GPL-3.0-or-later\n",
        "# Copyright (c) 2024-2026 Stevie Bellis.\n",
        "#\n",
        "# GENERATED by scripts/well/render-k8s-initdb.py from db/: do not edit.\n",
        "# The same init.sh, MANIFEST, ledger and migrations compose uses (ADR-101).\n",
        "# Role passwords come from the the-well-users secret via init.sh (\\getenv).\n",
        "\n",
        "apiVersion: v1\n",
        "kind: ConfigMap\n",
        "metadata:\n",
        "  name: the-well-initdb\n",
        "  namespace: unheaded\n",
        "data:\n",
        block("init.sh", (REPO / "db" / "init.sh").read_text()),
        block("MANIFEST", (MIG / "MANIFEST").read_text()),
        block("LEDGER.sql", (MIG / "LEDGER.sql").read_text()),
    ]
    for f in manifest_files():
        parts.append(block(f, (MIG / f).read_text()))
    return "".join(parts)


def main():
    out = render()
    if sys.argv[1:] == ["--check"]:
        if OUT.read_text() != out:
            print(f"{OUT.relative_to(REPO)} is stale: run scripts/well/render-k8s-initdb.py", file=sys.stderr)
            return 1
        print(f"{OUT.relative_to(REPO)} matches db/")
        return 0
    if sys.argv[1:]:
        print(__doc__, file=sys.stderr)
        return 2
    OUT.write_text(out)
    return 0


if __name__ == "__main__":
    sys.exit(main())
