"""scripts/sweep-ledger-step1.py runs ADR-090's sweep-order step 1 (S-TRUE-WIRE Steps 347-351, M-164).

Generated and vendored files are marked SKIPPED, never swept. The contract pinned here: only PENDING
rows move; SWEPT rows and rows whose file is gone are left alone; dry-run (the default) writes
nothing; every untouched line stays byte-identical."""
import importlib.util
import pathlib
import subprocess
import sys

import pytest

ROOT = pathlib.Path(__file__).resolve().parents[2]
SCRIPT = ROOT / "scripts" / "sweep-ledger-step1.py"
HEADER = "path\tstatus\tverdict\tcommit\tnotes\n"


@pytest.fixture(scope="module")
def step1():
    spec = importlib.util.spec_from_file_location("sweep_ledger_step1", SCRIPT)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def make_tree(tmp_path):
    files = {
        "pkg/a/a.go": "package a\n",
        "pkg/a/a.pb.go": "// Code generated by protoc-gen-go. DO NOT EDIT.\npackage a\n",
        "pkg/a/kind_string.go": "// Code generated by \"stringer -type=Kind\"; DO NOT EDIT.\npackage a\n",
        "pkg/a/gen.go": "// Code generated by hand-rolled-gen. DO NOT EDIT.\n\npackage a\n",
        "crates/x/src/gen.rs": "// @generated by build.rs\npub fn f() {}\n",
        "pkg/a/mentions.go": "package a\n\n// A comment that says Code generated ... DO NOT EDIT is not a marker.\n",
        "llama.cpp/ggml.c": "int x;\n",
        "crates/xv6-mbc/upstream/kernel/main.c": "int main(void){}\n",
        "doom/doom.h": "int y;\n",
        "LICENSES/MIT.txt": "MIT\n",
        "web/node_modules/left-pad/index.js": "module.exports = 1;\n",
        "pkg/b/b.pb.go": "// Code generated by protoc-gen-go. DO NOT EDIT.\npackage b\n",
    }
    for rel, body in files.items():
        p = tmp_path / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(body)
    rows = [
        "pkg/a/a.go\tPENDING\t\t\t",
        "pkg/a/a.pb.go\tPENDING\t\t\t",
        "pkg/a/kind_string.go\tPENDING\t\t\t",
        "pkg/a/gen.go\tPENDING\t\t\t",
        "crates/x/src/gen.rs\tPENDING\t\t\t",
        "pkg/a/mentions.go\tPENDING\t\t\t",
        "llama.cpp/ggml.c\tPENDING\t\t\t",
        "crates/xv6-mbc/upstream/kernel/main.c\tPENDING\t\t\t",
        "doom/doom.h\tPENDING\t\t\t",
        "LICENSES/MIT.txt\tPENDING\t\t\t",
        "web/node_modules/left-pad/index.js\tPENDING\t\t\t",
        "pkg/b/b.pb.go\tSWEPT\tCLEAN\tabc1234\t",
        "pkg/gone/gone.pb.go\tPENDING\t\t\t",
    ]
    ledger = tmp_path / "ledger.tsv"
    ledger.write_text(HEADER + "\n".join(rows) + "\n")
    return ledger


def run(ledger, root, *args):
    return subprocess.run(
        [sys.executable, "-I", str(SCRIPT), "--ledger", str(ledger), "--root", str(root), *args],
        capture_output=True, text=True, check=False)


def parse(ledger):
    lines = ledger.read_text().splitlines()[1:]
    return {ln.split("\t")[0]: ln.split("\t") for ln in lines}


def test_dry_run_is_default_and_writes_nothing(tmp_path):
    ledger = make_tree(tmp_path)
    before = ledger.read_bytes()
    r = run(ledger, tmp_path)
    assert r.returncode == 0, r.stderr
    assert ledger.read_bytes() == before
    assert "dry run" in r.stdout
    assert "generated 4" in r.stdout
    assert "vendored 5" in r.stdout


def test_apply_marks_generated_and_vendored_only(tmp_path):
    ledger = make_tree(tmp_path)
    r = run(ledger, tmp_path, "--apply")
    assert r.returncode == 0, r.stderr
    rows = parse(ledger)
    for gen in ("pkg/a/a.pb.go", "pkg/a/kind_string.go", "pkg/a/gen.go", "crates/x/src/gen.rs"):
        assert rows[gen][1] == "SKIPPED" and rows[gen][4] == "generated", gen
    for ven in ("llama.cpp/ggml.c", "crates/xv6-mbc/upstream/kernel/main.c", "doom/doom.h",
                "LICENSES/MIT.txt", "web/node_modules/left-pad/index.js"):
        assert rows[ven][1] == "SKIPPED" and rows[ven][4] == "vendored", ven
    # Hand-written code, a marker only quoted in a comment, and SWEPT rows do not move.
    assert rows["pkg/a/a.go"][1] == "PENDING"
    assert rows["pkg/a/mentions.go"][1] == "PENDING"
    assert rows["pkg/b/b.pb.go"] == ["pkg/b/b.pb.go", "SWEPT", "CLEAN", "abc1234", ""]
    # A row whose file is gone stays PENDING: the sweep decides what it means, not step 1.
    assert rows["pkg/gone/gone.pb.go"][1] == "PENDING"
    assert len(rows) == 13
    assert ledger.read_text().startswith(HEADER)


def test_apply_is_idempotent(tmp_path):
    ledger = make_tree(tmp_path)
    assert run(ledger, tmp_path, "--apply").returncode == 0
    once = ledger.read_bytes()
    r = run(ledger, tmp_path, "--apply")
    assert r.returncode == 0
    assert ledger.read_bytes() == once
    assert "generated 0" in r.stdout and "vendored 0" in r.stdout


def test_untouched_lines_are_byte_identical(tmp_path):
    ledger = make_tree(tmp_path)
    before = ledger.read_text().splitlines()
    assert run(ledger, tmp_path, "--apply").returncode == 0
    after = ledger.read_text().splitlines()
    assert len(before) == len(after)
    changed = [b for b, a in zip(before, after) if b != a]
    assert len(changed) == 9


def test_rejects_a_ledger_without_the_adr_090_header(tmp_path):
    ledger = tmp_path / "ledger.tsv"
    ledger.write_text("file\tstate\n")
    r = run(ledger, tmp_path, "--apply")
    assert r.returncode == 2
    assert ledger.read_text() == "file\tstate\n"


def test_classify(step1, tmp_path):
    (tmp_path / "x.go").write_text("// Code generated by x. DO NOT EDIT.\npackage x\n")
    assert step1.classify("x.go", tmp_path) == "generated"
    assert step1.classify("llama.cpp/a.c", tmp_path) == "vendored"
    assert step1.classify("missing.go", tmp_path) is None
