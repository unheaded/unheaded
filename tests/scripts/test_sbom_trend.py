"""check-sbom-trend counts third-party Rust components: what a Cargo.lock has from
a registry or git. A crate of this repository is not one, and neither is a lock
file's own format line. The script runs for real in a temp checkout; only `go
list` is a stand-in."""
import shutil
import stat
import subprocess
from pathlib import Path

import pytest

REPO = Path(__file__).resolve().parents[2]
HEADER = "# This file is automatically @generated by Cargo.\nversion = 4\n\n"
REGISTRY = 'source = "registry+https://github.com/rust-lang/crates.io-index"\n'


def package(name, version="1.0.0", source=REGISTRY):
    return f'[[package]]\nname = "{name}"\nversion = "{version}"\n{source}\n'


def checkout(tmp_path, locks, baseline):
    root = tmp_path / "repo"
    (root / "scripts").mkdir(parents=True)
    (root / "docs" / "policy").mkdir(parents=True)
    shutil.copy(REPO / "scripts" / "check-sbom-trend.sh", root / "scripts")
    (root / "docs" / "policy" / "sbom-count-baseline.txt").write_text(
        f"go_components=1\nrust_components={baseline}\npython_components=0\n")
    for name, text in locks.items():
        (root / name).mkdir()
        (root / name / "Cargo.lock").write_text(HEADER + text)
    subprocess.run(["git", "init", "-q", str(root)], check=True, timeout=30)
    subprocess.run(["git", "-C", str(root), "add", "."], check=True, timeout=30)
    tools = tmp_path / "bin"
    tools.mkdir()
    go = tools / "go"
    go.write_text("#!/bin/bash\nprintf 'main\\nexample.com/m v1\\n'\n")
    go.chmod(go.stat().st_mode | stat.S_IXUSR)
    return root, tools


def trend(root, tools, *args):
    return subprocess.run(["bash", "scripts/check-sbom-trend.sh", *args], cwd=root, capture_output=True, text=True,
                          timeout=30, check=False, env={"PATH": f"{tools}:/usr/bin:/bin"})


BASE = {"a": package("serde"), "b": package("tokio")}


def test_at_the_baseline_it_passes(tmp_path):
    r = trend(*checkout(tmp_path, BASE, 2))
    assert r.returncode == 0, r.stdout
    assert "OK rust_components: 2" in r.stdout


@pytest.mark.parametrize("name,text", [
    ("a third-party crate", package("serde") + package("left-pad")),
    ("another version of one", package("serde") + package("serde", "2.0.0")),
    ("one from git", package("serde") + package("forked", source='source = "git+https://example.invalid/f#abc"\n')),
])
def test_a_third_party_addition_fails(tmp_path, name, text):
    r = trend(*checkout(tmp_path, {**BASE, "a": text}, 2))
    assert r.returncode == 1, name
    assert "FAIL rust_components: 3 > baseline 2" in r.stdout


def test_a_crate_of_this_repository_is_not_third_party(tmp_path):
    r = trend(*checkout(tmp_path, {**BASE, "a": package("serde") + package("first-party", source="")}, 2))
    assert r.returncode == 0, r.stdout
    assert "OK rust_components: 2" in r.stdout


def test_a_lock_files_format_line_is_no_component(tmp_path):
    r = trend(*checkout(tmp_path, {**BASE, "c": package("first-party", source="")}, 2))
    assert r.returncode == 0, r.stdout
    assert "OK rust_components: 2" in r.stdout


def test_the_last_package_of_a_lock_is_counted(tmp_path):
    r = trend(*checkout(tmp_path, {"a": package("serde") + package("tail-crate")}, 1))
    assert r.returncode == 1, r.stdout


def test_update_never_raises_the_baseline(tmp_path):
    root, tools = checkout(tmp_path, {**BASE, "a": package("serde") + package("left-pad")}, 2)
    trend(root, tools, "--update")
    assert "rust_components=2\n" in (root / "docs/policy/sbom-count-baseline.txt").read_text()
